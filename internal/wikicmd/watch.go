package wikicmd

import (
	"database/sql"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/fsnotify/fsnotify"
	_ "modernc.org/sqlite"

	"wiki_skill/internal/embedworker"
	"wiki_skill/internal/index"
)

func addDirsRecursively(watcher *fsnotify.Watcher, root string) error {
	return filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		if d.Name() == ".wiki" || d.Name() == ".git" {
			return filepath.SkipDir
		}
		return watcher.Add(path)
	})
}

// RunWatch watches root for note changes and incrementally updates the
// semantic index. It runs on a single goroutine: filesystem events and the
// debounce timer are both read from the same select loop, so there is no
// concurrent access to the pending-change sets.
func RunWatch(root string, embed embedworker.Embedder, debounce time.Duration, stderr io.Writer, onBatch func(upserted, removed []string)) error {
	dbPath := filepath.Join(root, ".wiki", "index.sqlite")
	if err := os.MkdirAll(filepath.Dir(dbPath), 0o755); err != nil {
		return err
	}
	db, err := sql.Open("sqlite", dbPath)
	if err != nil {
		return err
	}
	defer db.Close()
	if err := index.InitDB(db); err != nil {
		return err
	}

	watcher, err := fsnotify.NewWatcher()
	if err != nil {
		return err
	}
	defer watcher.Close()

	if err := addDirsRecursively(watcher, root); err != nil {
		return err
	}

	changed := map[string]bool{}
	deleted := map[string]bool{}

	var debounceTimer *time.Timer
	var debounceC <-chan time.Time

	resetDebounce := func() {
		if debounceTimer == nil {
			debounceTimer = time.NewTimer(debounce)
		} else {
			if !debounceTimer.Stop() {
				select {
				case <-debounceTimer.C:
				default:
				}
			}
			debounceTimer.Reset(debounce)
		}
		debounceC = debounceTimer.C
	}

	flush := func() {
		changedPaths := make([]string, 0, len(changed))
		for p := range changed {
			changedPaths = append(changedPaths, p)
		}
		deletedPaths := make([]string, 0, len(deleted))
		for p := range deleted {
			deletedPaths = append(deletedPaths, p)
		}
		changed = map[string]bool{}
		deleted = map[string]bool{}
		debounceC = nil
		if len(changedPaths) == 0 && len(deletedPaths) == 0 {
			return
		}
		upserted, removed, err := ProcessBatch(root, db, changedPaths, deletedPaths, embed)
		if err != nil {
			fmt.Fprintf(stderr, "wiki watch: batch failed: %v\n", err)
			return
		}
		if onBatch != nil && (len(upserted) > 0 || len(removed) > 0) {
			onBatch(upserted, removed)
		}
	}

	for {
		select {
		case event, ok := <-watcher.Events:
			if !ok {
				return nil
			}
			if strings.Contains(event.Name, string(filepath.Separator)+".wiki") {
				continue
			}
			if event.Op&fsnotify.Create != 0 {
				if info, statErr := os.Stat(event.Name); statErr == nil && info.IsDir() {
					if err := addDirsRecursively(watcher, event.Name); err != nil {
						fmt.Fprintf(stderr, "wiki watch: failed to watch new directory %s: %v\n", event.Name, err)
					}
					continue
				}
			}
			// _index.md is generated by this loop's own batches; reacting to it would loop.
			if !strings.HasSuffix(event.Name, ".md") || isVaultIndex(event.Name) {
				continue
			}
			switch {
			case event.Op&(fsnotify.Remove|fsnotify.Rename) != 0:
				delete(changed, event.Name)
				deleted[event.Name] = true
			case event.Op&(fsnotify.Create|fsnotify.Write) != 0:
				delete(deleted, event.Name)
				changed[event.Name] = true
			default:
				continue
			}
			resetDebounce()
		case <-debounceC:
			flush()
		case watchErr, ok := <-watcher.Errors:
			if !ok {
				return nil
			}
			fmt.Fprintf(stderr, "wiki watch: watcher error: %v\n", watchErr)
		}
	}
}
