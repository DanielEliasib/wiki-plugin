// addDirsRecursively watches dir and every folder under it, except hidden ones (the Vault root itself is always
// watched).
func addDirsRecursively(watcher *fsnotify.Watcher, root, dir string) error {
	return filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		if path != root && vault.IsHiddenName(d.Name()) {
			return filepath.SkipDir
		}
		return watcher.Add(path)
	})
}

// RunWatch watches root for note changes and incrementally updates the
// semantic index; it first applies whatever changed while nothing was watching. It runs on a single goroutine: filesystem events and the
// debounce timer are both read from the same select loop, so there is no
// concurrent access to the pending-change sets.
func RunWatch(root string, embed embedworker.Embedder, debounce time.Duration, stderr io.Writer, onBatch func(upserted, removed []string)) error {
	db, err := index.Open(root)
	if err != nil {
		return err
	}
	defer db.Close()

	watcher, err := fsnotify.NewWatcher()
	if err != nil {
		return err
	}
	defer watcher.Close()

	if err := addDirsRecursively(watcher, root, root); err != nil {
		return err
	}

	pending := newPendingSet()
	applyBatch := func(changed, deleted []string) (Outcome, error) {
		return Apply(root, changed, deleted, embed)
	}

	var timer *time.Timer
	var timerC <-chan time.Time
	// wait (re)starts the single timer: the debounce after an event, the retry delay after a failure.
	wait := func(d time.Duration) {
		if timer == nil {
			timer = time.NewTimer(d)
		} else {
			if !timer.Stop() {
				select {
				case <-timer.C:
				default:
				}
			}
			timer.Reset(d)
		}
		timerC = timer.C
	}

	// What changed while nothing was watching: queue it like any other change (an unchanged note costs a hash
	// comparison, nothing is embedded for it).
	if changed, gone, err := catchUp(root); err != nil {
		fmt.Fprintf(stderr, "wiki watch: could not check what changed before it started: %v\n", err)
	} else {
		for _, p := range changed {
			pending.Add(p, false)
		}
		for _, p := range gone {
			pending.Add(p, true)
		}
		if !pending.Empty() {
			wait(10 * time.Millisecond)
		}
	}

	for {
		select {
		case event, ok := <-watcher.Events:
			if !ok {
				return nil
			}
			if event.Op&fsnotify.Create != 0 {
				if info, statErr := os.Stat(event.Name); statErr == nil && info.IsDir() {
					if err := addDirsRecursively(watcher, root, event.Name); err != nil {
						fmt.Fprintf(stderr, "wiki watch: failed to watch new directory %s: %v\n", event.Name, err)
					}
					continue
				}
			}
			// _index.md is generated by Apply; reacting to it would loop. Hidden folders and other files are no Notes.
			if !isNotePath(root, event.Name) {
				continue
			}
			switch {
			case event.Op&(fsnotify.Remove|fsnotify.Rename) != 0:
				pending.Add(event.Name, true)
			case event.Op&(fsnotify.Create|fsnotify.Write) != 0:
				pending.Add(event.Name, false)
			default:
				continue
			}
			wait(debounce)
		case <-timerC:
			timerC = nil
			if delay := watchStep(pending, applyBatch, stderr, onBatch); delay > 0 {
				wait(delay)
			} else if !pending.Empty() {
				wait(debounce)
			}
		case watchErr, ok := <-watcher.Errors:
			if !ok {
				return nil
			}
			fmt.Fprintf(stderr, "wiki watch: watcher error: %v\n", watchErr)
		}
	}
}
